-- PostgreSQL schema for Amader Khamar. Run with: npm run db:init
-- This is additive (CREATE IF NOT EXISTS) and does not erase farm records.
CREATE TABLE IF NOT EXISTS users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, email TEXT NOT NULL UNIQUE,
  name TEXT NOT NULL, password_hash TEXT NOT NULL,
  role TEXT NOT NULL CHECK(role IN ('admin','staff')),
  created_at TEXT NOT NULL DEFAULT (to_char(timezone('UTC',now()),'YYYY-MM-DD HH24:MI:SS'))
);
CREATE TABLE IF NOT EXISTS sessions (
  token_hash TEXT PRIMARY KEY, user_id INTEGER NOT NULL REFERENCES users(id),
  expires_at TEXT NOT NULL,
  created_at TEXT NOT NULL DEFAULT (to_char(timezone('UTC',now()),'YYYY-MM-DD HH24:MI:SS'))
);
CREATE TABLE IF NOT EXISTS beds (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, code TEXT NOT NULL UNIQUE,
  capacity_kg NUMERIC(16,3) CHECK(capacity_kg IS NULL OR capacity_kg > 0),
  enabled INTEGER NOT NULL DEFAULT 1, notes TEXT NOT NULL DEFAULT ''
);
CREATE TABLE IF NOT EXISTS slots (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, code TEXT NOT NULL UNIQUE,
  capacity_kg NUMERIC(16,3) CHECK(capacity_kg IS NULL OR capacity_kg > 0),
  enabled INTEGER NOT NULL DEFAULT 1, notes TEXT NOT NULL DEFAULT ''
);
CREATE TABLE IF NOT EXISTS slot_lots (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, slot_id INTEGER NOT NULL REFERENCES slots(id),
  received_on TEXT NOT NULL, ready_not_before TEXT NOT NULL,
  initial_kg NUMERIC(16,3) NOT NULL CHECK(initial_kg > 0),
  remaining_kg NUMERIC(16,3) NOT NULL CHECK(remaining_kg >= 0),
  material_cost_bdt NUMERIC(16,2) NOT NULL DEFAULT 0 CHECK(material_cost_bdt >= 0),
  approved_on TEXT, notes TEXT NOT NULL DEFAULT '',
  created_at TEXT NOT NULL DEFAULT (to_char(timezone('UTC',now()),'YYYY-MM-DD HH24:MI:SS'))
);
CREATE TABLE IF NOT EXISTS batches (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, bed_id INTEGER NOT NULL REFERENCES beds(id),
  started_on TEXT NOT NULL, min_ready_on TEXT NOT NULL, max_ready_on TEXT NOT NULL,
  input_kg NUMERIC(16,3) NOT NULL CHECK(input_kg > 0),
  expected_output_kg NUMERIC(16,3) CHECK(expected_output_kg IS NULL OR expected_output_kg >= 0),
  worm_count INTEGER CHECK(worm_count IS NULL OR worm_count >= 0),
  status TEXT NOT NULL DEFAULT 'active' CHECK(status IN ('active','harvested')),
  notes TEXT NOT NULL DEFAULT '',
  created_at TEXT NOT NULL DEFAULT (to_char(timezone('UTC',now()),'YYYY-MM-DD HH24:MI:SS'))
);
CREATE UNIQUE INDEX IF NOT EXISTS one_active_batch_per_bed ON batches(bed_id) WHERE status='active';
CREATE TABLE IF NOT EXISTS batch_feed (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, batch_id INTEGER NOT NULL REFERENCES batches(id),
  slot_lot_id INTEGER NOT NULL REFERENCES slot_lots(id), quantity_kg NUMERIC(16,3) NOT NULL CHECK(quantity_kg > 0),
  fed_on TEXT NOT NULL,
  created_at TEXT NOT NULL DEFAULT (to_char(timezone('UTC',now()),'YYYY-MM-DD HH24:MI:SS'))
);
CREATE TABLE IF NOT EXISTS care_logs (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, batch_id INTEGER NOT NULL REFERENCES batches(id),
  logged_on TEXT NOT NULL, moisture_pct NUMERIC(8,3), temp_c NUMERIC(8,3),
  action TEXT NOT NULL, notes TEXT NOT NULL DEFAULT '',
  created_at TEXT NOT NULL DEFAULT (to_char(timezone('UTC',now()),'YYYY-MM-DD HH24:MI:SS'))
);
CREATE TABLE IF NOT EXISTS harvests (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  batch_id INTEGER NOT NULL UNIQUE REFERENCES batches(id), harvested_on TEXT NOT NULL,
  quantity_kg NUMERIC(16,3) NOT NULL CHECK(quantity_kg > 0), notes TEXT NOT NULL DEFAULT '',
  created_at TEXT NOT NULL DEFAULT (to_char(timezone('UTC',now()),'YYYY-MM-DD HH24:MI:SS'))
);
CREATE TABLE IF NOT EXISTS products (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, sku TEXT NOT NULL UNIQUE,
  name TEXT NOT NULL, category TEXT NOT NULL DEFAULT 'compost', description TEXT NOT NULL DEFAULT '',
  unit TEXT NOT NULL DEFAULT 'kg', compost_kg_per_unit NUMERIC(16,3) NOT NULL DEFAULT 0,
  price_bdt NUMERIC(16,2) NOT NULL DEFAULT 0 CHECK(price_bdt >= 0),
  published INTEGER NOT NULL DEFAULT 0, enabled INTEGER NOT NULL DEFAULT 1,
  created_at TEXT NOT NULL DEFAULT (to_char(timezone('UTC',now()),'YYYY-MM-DD HH24:MI:SS'))
);
CREATE TABLE IF NOT EXISTS stock_movements (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, product_id INTEGER NOT NULL REFERENCES products(id),
  qty NUMERIC(16,3) NOT NULL CHECK(qty <> 0), reason TEXT NOT NULL,
  ref_type TEXT NOT NULL DEFAULT '', ref_id INTEGER, notes TEXT NOT NULL DEFAULT '',
  created_at TEXT NOT NULL DEFAULT (to_char(timezone('UTC',now()),'YYYY-MM-DD HH24:MI:SS'))
);
CREATE TABLE IF NOT EXISTS orders (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, code TEXT NOT NULL UNIQUE,
  customer_name TEXT NOT NULL, phone TEXT NOT NULL, address TEXT NOT NULL, notes TEXT NOT NULL DEFAULT '',
  status TEXT NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','confirmed','packed','delivered','cancelled')),
  payment_status TEXT NOT NULL DEFAULT 'unpaid' CHECK(payment_status IN ('unpaid','paid','refunded')),
  amount_bdt NUMERIC(16,2) NOT NULL, delivery_fee_bdt NUMERIC(16,2) NOT NULL DEFAULT 0,
  created_at TEXT NOT NULL DEFAULT (to_char(timezone('UTC',now()),'YYYY-MM-DD HH24:MI:SS')),
  paid_at TEXT, delivered_at TEXT
);
CREATE TABLE IF NOT EXISTS order_items (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id INTEGER NOT NULL REFERENCES orders(id), product_id INTEGER NOT NULL REFERENCES products(id),
  product_name TEXT NOT NULL, qty NUMERIC(16,3) NOT NULL CHECK(qty > 0),
  unit_price_bdt NUMERIC(16,2) NOT NULL CHECK(unit_price_bdt >= 0)
);
CREATE TABLE IF NOT EXISTS expenses (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, spent_on TEXT NOT NULL,
  category TEXT NOT NULL, amount_bdt NUMERIC(16,2) NOT NULL CHECK(amount_bdt > 0),
  notes TEXT NOT NULL DEFAULT '',
  created_at TEXT NOT NULL DEFAULT (to_char(timezone('UTC',now()),'YYYY-MM-DD HH24:MI:SS'))
);
CREATE TABLE IF NOT EXISTS tasks (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, title TEXT NOT NULL,
  description TEXT NOT NULL DEFAULT '', due_on TEXT NOT NULL,
  priority TEXT NOT NULL DEFAULT 'normal' CHECK(priority IN ('urgent','normal','low')),
  status TEXT NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','done')),
  created_at TEXT NOT NULL DEFAULT (to_char(timezone('UTC',now()),'YYYY-MM-DD HH24:MI:SS'))
);
CREATE TABLE IF NOT EXISTS posts (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, slug TEXT NOT NULL UNIQUE,
  title TEXT NOT NULL, category TEXT NOT NULL DEFAULT 'blog',
  excerpt TEXT NOT NULL DEFAULT '', body TEXT NOT NULL DEFAULT '',
  published INTEGER NOT NULL DEFAULT 0,
  created_at TEXT NOT NULL DEFAULT (to_char(timezone('UTC',now()),'YYYY-MM-DD HH24:MI:SS'))
);
CREATE TABLE IF NOT EXISTS inquiries (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT NOT NULL,
  phone TEXT NOT NULL, subject TEXT NOT NULL, message TEXT NOT NULL DEFAULT '',
  status TEXT NOT NULL DEFAULT 'new' CHECK(status IN ('new','contacted','closed')),
  created_at TEXT NOT NULL DEFAULT (to_char(timezone('UTC',now()),'YYYY-MM-DD HH24:MI:SS'))
);
CREATE TABLE IF NOT EXISTS settings (key TEXT PRIMARY KEY, value TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS audit (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_id INTEGER, action TEXT NOT NULL, entity TEXT NOT NULL,
  entity_id INTEGER, details TEXT NOT NULL DEFAULT '',
  created_at TEXT NOT NULL DEFAULT (to_char(timezone('UTC',now()),'YYYY-MM-DD HH24:MI:SS'))
);
-- Idempotent compatibility for older schema versions.
ALTER TABLE posts ADD COLUMN IF NOT EXISTS category TEXT NOT NULL DEFAULT 'blog';
